const DEFAULT_BACKEND_ORIGIN = 'http://127.0.0.1:8000'
const SESSION_TOKEN_KEY = 'ultron-auth-token'
const LAUNCH_SECRET_HEADER = 'X-Ultron-Launch-Secret'

function isPackagedRenderer() {
  return typeof window !== 'undefined' && window.location.protocol === 'ultron:'
}

function getRuntimeQueryValue(name) {
  if (typeof window === 'undefined') return ''

  try {
    return new URLSearchParams(window.location.search).get(name) || ''
  } catch {
    return ''
  }
}

function getRuntimeBackendOrigin() {
  const rawPort = getRuntimeQueryValue('ultronPort')

  // Electron supplies one ephemeral loopback port. Accept only a canonical
  // decimal TCP port so a query parameter can never become part of the URL.
  if (!/^[1-9]\d{0,4}$/.test(rawPort)) {
    return isPackagedRenderer() ? '' : DEFAULT_BACKEND_ORIGIN
  }

  const port = Number(rawPort)
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    return isPackagedRenderer() ? '' : DEFAULT_BACKEND_ORIGIN
  }

  return `http://127.0.0.1:${port}`
}

function getRuntimeLaunchSecret() {
  const secret = getRuntimeQueryValue('ultronLaunchSecret')

  // A launch capability generated by Electron is URL-safe ASCII. Keeping the
  // value bounded and free of control characters prevents invalid HTTP headers.
  return /^[\x21-\x7e]{1,512}$/.test(secret) ? secret : ''
}

/**
 * The packaged Electron app starts ULTRON on an ephemeral loopback port and
 * passes that port through the initial app URL. Vite keeps the familiar 8000
 * fallback for development only. A packaged renderer refuses to guess a
 * backend address if its authenticated launch channel is missing.
 */
export const BACKEND_ORIGIN = getRuntimeBackendOrigin()
export const ULTRON_LAUNCH_SECRET = getRuntimeLaunchSecret()
const BACKEND_URL = BACKEND_ORIGIN ? new URL(BACKEND_ORIGIN) : null

let originalFetch = null
let fetchInstalled = false
const unauthorizedListeners = new Set()

function getBrowserStorage() {
  try {
    return window.sessionStorage
  } catch {
    return null
  }
}

function getRequestUrl(input) {
  const value = input instanceof Request
    ? input.url
    : input instanceof URL
      ? input.href
      : typeof input === 'string'
        ? input
        : input?.url

  if (!value) return null

  try {
    return new URL(value, window.location.href)
  } catch {
    return null
  }
}

function isLocalBackendUrl(url) {
  return Boolean(BACKEND_URL && url && url.origin === BACKEND_URL.origin)
}

function assertBackendChannel() {
  if (!BACKEND_ORIGIN) {
    throw new Error('The ULTRON desktop channel is unavailable. Restart ULTRON.')
  }

  if (isPackagedRenderer() && !ULTRON_LAUNCH_SECRET) {
    throw new Error('The ULTRON desktop channel could not be verified. Restart ULTRON.')
  }
}

function shouldClearSessionOnUnauthorized(url) {
  const path = url?.pathname || ''

  if (!path.startsWith('/api/auth/')) return true

  return ['/api/auth/me', '/api/auth/logout'].includes(path)
}

function mergeHeaders(input, init) {
  const headers = new Headers(input instanceof Request ? input.headers : undefined)

  if (init?.headers) {
    new Headers(init.headers).forEach((value, key) => headers.set(key, value))
  }

  return headers
}

function withBackendHeaders(input, init, token) {
  const headers = mergeHeaders(input, init)

  if (token && !headers.has('Authorization')) {
    headers.set('Authorization', `Bearer ${token}`)
  }

  if (ULTRON_LAUNCH_SECRET && !headers.has(LAUNCH_SECRET_HEADER)) {
    headers.set(LAUNCH_SECRET_HEADER, ULTRON_LAUNCH_SECRET)
  }

  if (input instanceof Request) {
    return [new Request(input, { ...init, headers }), undefined]
  }

  return [input, { ...init, headers }]
}

function notifyUnauthorized(url) {
  clearSessionToken()

  unauthorizedListeners.forEach(listener => {
    try {
      listener(url)
    } catch {
      // A failed listener must never interrupt the original request flow.
    }
  })
}

/**
 * Stores the local account session only for the current app session. It is
 * deliberately not persisted in localStorage, which keeps shared computers
 * from reopening another operator's session after the app is closed.
 */
export function getSessionToken() {
  return getBrowserStorage()?.getItem(SESSION_TOKEN_KEY) || ''
}

function desktopSessionBridge() {
  if (typeof window === 'undefined') return null
  const bridge = window.ultronDesktop
  if (!bridge || typeof bridge !== 'object') return null
  return bridge
}

function syncDesktopSessionToken(token) {
  const bridge = desktopSessionBridge()
  if (typeof bridge?.syncSessionToken !== 'function') return Promise.resolve(false)

  return Promise.resolve(bridge.syncSessionToken(token)).then(
    result => result?.ok === true,
    () => false,
  )
}

function clearDesktopSessionToken() {
  const bridge = desktopSessionBridge()
  if (typeof bridge?.clearSessionToken !== 'function') return Promise.resolve(false)

  return Promise.resolve(bridge.clearSessionToken()).then(
    result => result?.ok === true,
    () => false,
  )
}

export function setSessionToken(token) {
  const value = String(token || '')
  if (!value) return clearSessionToken()
  getBrowserStorage()?.setItem(SESSION_TOKEN_KEY, value)
  return syncDesktopSessionToken(value)
}

export function clearSessionToken() {
  getBrowserStorage()?.removeItem(SESSION_TOKEN_KEY)
  return clearDesktopSessionToken()
}

/**
 * Previous ULTRON versions stored interface preferences under shared keys.
 * They are intentionally removed during the account upgrade so a precise
 * location or UI setting cannot carry from one local account into another.
 */
export function clearLegacySharedUiState() {
  try {
    window.localStorage.removeItem('ultron-preferences')
    window.localStorage.removeItem('ultron-weather')
  } catch {
    // Storage may be unavailable in a locked-down browser context.
  }
}

/**
 * Adds the current local session to requests addressed to ULTRON's loopback
 * backend only. Requests to integrations such as weather services are passed
 * through unchanged.
 */
export function installAuthenticatedFetch(onUnauthorized) {
  if (typeof window === 'undefined' || typeof window.fetch !== 'function') {
    return () => {}
  }

  if (typeof onUnauthorized === 'function') {
    unauthorizedListeners.add(onUnauthorized)
  }

  if (!fetchInstalled) {
    originalFetch = window.fetch.bind(window)

    window.fetch = async (input, init) => {
      const url = getRequestUrl(input)
      const token = getSessionToken()
      const targetsBackend = isLocalBackendUrl(url)
      const [requestInput, requestInit] = targetsBackend
        ? withBackendHeaders(input, init, token)
        : [input, init]

      const response = await originalFetch(requestInput, requestInit)

      if (targetsBackend && response.status === 401 && shouldClearSessionOnUnauthorized(url)) {
        notifyUnauthorized(url)
      }

      return response
    }

    fetchInstalled = true
  }

  return () => {
    if (typeof onUnauthorized === 'function') {
      unauthorizedListeners.delete(onUnauthorized)
    }

    if (fetchInstalled && unauthorizedListeners.size === 0 && originalFetch) {
      window.fetch = originalFetch
      originalFetch = null
      fetchInstalled = false
    }
  }
}

async function readResponse(response) {
  try {
    return await response.json()
  } catch {
    return {}
  }
}

async function authRequest(path, options = {}) {
  assertBackendChannel()
  const headers = new Headers(options.headers)

  // AuthGate installs the global wrapper before it calls this function. Add the
  // launch capability here too, so direct auth calls remain valid in isolation.
  if (ULTRON_LAUNCH_SECRET && !headers.has(LAUNCH_SECRET_HEADER)) {
    headers.set(LAUNCH_SECRET_HEADER, ULTRON_LAUNCH_SECRET)
  }

  const response = await fetch(`${BACKEND_ORIGIN}${path}`, {
    ...options,
    headers,
  })
  const payload = await readResponse(response)

  if (!response.ok || payload.ok === false) {
    const message = payload.detail || payload.error || payload.message || 'Authentication request failed.'
    const error = new Error(message)
    error.status = response.status
    error.payload = payload
    throw error
  }

  return payload
}

function json(body) {
  return {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  }
}

export function getAuthConfig() {
  return authRequest('/api/auth/config')
}

export function registerAccount({ email, password, displayName }) {
  return authRequest('/api/auth/register', json({
    email,
    password,
    display_name: displayName || undefined,
  }))
}

export function loginAccount({ email, password }) {
  return authRequest('/api/auth/login', json({ email, password }))
}

export function getCurrentAccount() {
  return authRequest('/api/auth/me')
}

export function logoutAccount() {
  return authRequest('/api/auth/logout', { method: 'POST' })
}

export function verifyEmail(token) {
  return authRequest('/api/auth/verify-email', json({ token }))
}

export function resendVerification(email) {
  return authRequest('/api/auth/resend-verification', json({ email }))
}

export function requestPasswordReset(email) {
  return authRequest('/api/auth/request-password-reset', json({ email }))
}

export function resetPassword({ token, password }) {
  return authRequest('/api/auth/reset-password', json({ token, password }))
}
